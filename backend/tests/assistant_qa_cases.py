def fixture_context():
    """Read the actual JSON fixtures independently of production loaders."""
    context = json.loads((ROOT / "backend/tests/fixtures/rotation_context.synthetic.json").read_text(encoding="utf-8"))
    context["profile"] = json.loads((ROOT / "data/fixtures/farm.synthetic.json").read_text(encoding="utf-8"))
    return context


def candidate_id(context, alias):
    # Fixture aliases come from ID suffixes, never candidate order or rank.
    matches = [c["candidate_id"] for c in context["analysis"]["candidates"]
               if c["candidate_id"].rsplit("-", 1)[-1] == alias]
    if len(matches) != 1:
        raise AssertionError(f"Fixture does not uniquely define candidate alias {alias}")
    return matches[0]


def case_context(case):
    context = fixture_context()
    mutation = case.mutation
    if mutation == "null_demand":
        context["analysis"]["candidates"][0]["water_budget"]["demand_mm"] = None
    elif mutation == "missing_rank":
        for candidate in context["analysis"]["candidates"]:
            candidate.pop("rank", None)
    elif mutation == "missing_candidates":
        context["analysis"].pop("candidates")
    elif mutation == "missing_differences":
        context["scenario"].pop("differences")
    elif mutation == "missing_irrigation":
        context["profile"].pop("irrigation_supply_mm_per_season")
    elif mutation == "selected_b":
        context["candidate_id"] = candidate_id(context, "b")
    elif mutation == "unknown_selection":
        context["candidate_id"] = "not-supplied"
    return context


METRICS = {
    "demand": "demand_mm", "rainfall": "rainfall_mm",
    "effective rainfall": "effective_rainfall_mm", "irrigation supply": "irrigation_supply_mm",
    "deficit": "deficit_mm",
}
NUMBER = r"-?\d+(?:\.\d+)?"


def assert_grounded_sections(test, context, answer):
    """Check every displayed structured number against its owning fixture record."""
    flat = " ".join(answer.split())
    pieces = re.split(r"(?=Baseline analysis |Hypothetical scenario |Observation record )", flat)
    for piece in pieces:
        if piece.startswith("Baseline analysis "):
            record = context.get("analysis", {})
        elif piece.startswith("Hypothetical scenario "):
            record = context.get("scenario", {})
            change = record.get("parameters", {}).get("rainfall_change_pct")
            if "Supplied rainfall change:" in piece:
                test.assertIn(f"rainfall change: {change}%" if change is not None else "rainfall change: unknown", piece)
            test.assertIn("hypothetical", piece.lower())
        elif piece.startswith("Observation record "):
            record = context.get("observations", {})
            if "Observation period:" in piece:
                period = record.get("period", {})
                test.assertIn(f"{period.get('start')} to {period.get('end')}", piece)
                for key, label, unit in (("rainfall_mm", "rainfall", "mm"),
                                         ("mean_temperature_c", "mean temperature", "Celsius")):
                    value = record.get("summary", {}).get(key)
                    test.assertIn(f"{label}: {value} {unit}" if value is not None else f"{label}: unknown", piece)
        else:
            continue
        test.assertIn("synthetic", piece.lower())
        for entry in record.get("assumptions", []) + record.get("limitations", []):
            test.assertIn(entry, piece)
        sources = re.search(r"Source references \(supplied IDs only\): (.*?)\. Assumptions:", piece)
        test.assertIsNotNone(sources, "Missing source metadata")
        expected_refs = record.get("source_refs") or []
        if expected_refs:
            test.assertEqual(sources.group(1).split("; "), expected_refs)
        else:
            test.assertIn("unknown", sources.group(1))
        candidates = {c["candidate_id"]: c for c in record.get("candidates", []) or []}
        differences = {c["candidate_id"]: c for c in record.get("differences", []) or []}
        chunks = re.findall(r"Candidate ([\w-]+): (.*?)(?=Candidate [\w-]+:|Source references|Ranks are|$)", piece)
        for identifier, chunk in chunks:
            test.assertIn(identifier, candidates, "Output references an unknown candidate")
            candidate = candidates[identifier]
            delta = "scenario minus baseline" in chunk
            owner = differences.get(identifier, {}) if delta else candidate
            for label, value, unit in re.findall(
                rf"(effective rainfall|irrigation supply|demand|rainfall|deficit): (unknown|{NUMBER})(?: (mm))?", chunk
            ):
                expected = owner.get("water_budget", {}).get(METRICS[label])
                if expected is None:
                    test.assertEqual(value, "unknown")
                else:
                    test.assertEqual(float(value), expected, f"{identifier}: wrong {label}")
                    test.assertEqual(unit, "mm", f"{identifier}: missing water unit")
            for label, value in re.findall(rf"supplied (rank|score) (unknown|{NUMBER})", chunk):
                expected = candidate.get(label)
                test.assertEqual(value, "unknown" if expected is None else str(expected))
            score_delta = re.search(rf"score difference \(scenario minus baseline\): (unknown|{NUMBER})", chunk)
            if score_delta:
                expected = owner.get("score_delta")
                test.assertEqual(score_delta.group(1), "unknown" if expected is None else str(expected))
            period = candidate.get("water_budget", {}).get("period", {})
            if not delta and "Water budget period:" in chunk:
                test.assertIn(f"period: {period.get('start', 'unknown')} to {period.get('end', 'unknown')}", chunk)
            if "Effective rainfall assumption:" in chunk:
                test.assertIn(candidate["water_budget"]["effective_rainfall_assumption"], chunk)
            if "Supplied reasons:" in chunk:
                for reason in candidate.get("reasons", []):
                    test.assertIn(reason, chunk)
            for season, crop in re.findall(r"season (\d+): crop ID ([\w-]+)", chunk):
                test.assertIn({"season_index": int(season), "crop_id": crop}, candidate["sequence"])
            for component, value, weight, direction in re.findall(
                rf"([\w-]+): value ({NUMBER}), weight ({NUMBER}), direction ([\w_]+)", chunk
            ):
                expected = candidate["score_components"][component]
                test.assertEqual((float(value), float(weight), direction),
                                 (expected["value"], expected["weight"], expected["direction"]))


def assert_case(test, case, context, answer):
    """Independent semantic assertions, shared by direct and subprocess tests."""
    flat = " ".join(answer.split())
    test.assertIn("synthetic", flat.lower(), "Every fixture answer must disclose synthetic data")
    test.assertNotIn("999", flat, "A question's fabricated value leaked into the answer")
    test.assertNotRegex(flat, r"https?://", "Fixture has IDs only, not citation URLs")
    profile = context["profile"]
    kind = case.kind
    if kind in {"unavailable", "unknown_candidate"}:
        test.assertRegex(flat.lower(), r"unknown|unavailable|unsupported|cannot|conflict|ambiguous")
        test.assertNotIn("supplied score", flat)
        test.assertNotIn("Water budget period:", flat)
        test.assertNotIn("Observation period:", flat)
        return
    if kind in {"name", "area", "location", "irrigation", "soil", "history"}:
        test.assertNotIn("Baseline analysis", flat)
        if kind == "name":
            test.assertIn(profile["name"], flat)
        elif kind == "area":
            test.assertIn(f"{profile['area_ha']} hectares", flat)
        elif kind == "location":
            test.assertIn(f"latitude {profile['location']['latitude']}", flat)
            test.assertIn(f"longitude {profile['location']['longitude']}", flat)
        else:
            test.assertIn("unknown", flat.lower())
            topic = {"irrigation": "irrigation supply", "soil": "soil", "history": "crop history"}[kind]
            test.assertIn(topic, flat.lower())
            if kind == "irrigation":
                test.assertNotRegex(flat, rf"{NUMBER} mm")
        return

    assert_grounded_sections(test, context, answer)
    water_kinds = {"water", "deficit", "water_compare", "deficit_compare", "scenario"}
    selected_id = candidate_id(context, case.candidate) if case.candidate else None
    expected_candidates = context["analysis"].get("candidates", [])
    if selected_id:
        expected_candidates = [c for c in expected_candidates if c["candidate_id"] == selected_id]
        for candidate in context["analysis"]["candidates"]:
            if candidate["candidate_id"] != selected_id:
                test.assertNotIn(f"Candidate {candidate['candidate_id']}:", flat)
    if kind in water_kinds:
        for candidate in expected_candidates:
            test.assertIn(f"Candidate {candidate['candidate_id']}:", flat)
            budget = candidate["water_budget"]
            labels = {"deficit": "deficit_mm"} if kind in {"deficit", "deficit_compare"} else METRICS
            for label, field in labels.items():
                value = budget.get(field)
                test.assertIn(f"{label}: {value} mm" if value is not None else f"{label}: unknown", flat)
        test.assertNotIn("Observation record", flat)
        test.assertNotIn("Supplied crop sequence", flat)
        if kind != "scenario":
            test.assertNotIn("supplied score", flat)
        if kind in {"water", "deficit"}:
            test.assertNotIn("Hypothetical scenario", flat)
        else:
            test.assertIn("Hypothetical scenario", flat)
            test.assertIn("not a rainfall observation or forecast", flat)
            if case.mutation == "missing_differences":
                test.assertIn("differences are unknown", flat)
            else:
                test.assertIn("scenario minus baseline", flat)
    elif kind in {"rank", "details"}:
        for candidate in expected_candidates:
            rank = candidate.get("rank")
            test.assertIn(f"supplied rank {rank}" if rank is not None else "supplied rank unknown", flat)
            test.assertIn(f"supplied score {candidate['score']}", flat)
            for reason in candidate["reasons"]:
                test.assertIn(reason, flat)
        for unrelated in ("Hypothetical scenario", "Observation record", "Water budget period:"):
            test.assertNotIn(unrelated, flat)
        if kind == "rank":
            test.assertNotIn("Supplied crop sequence", flat)
        else:
            test.assertIn("Supplied crop sequence", flat)
    elif kind == "observations":
        test.assertIn("Observation record", flat)
        test.assertNotIn("Baseline analysis", flat)
        test.assertNotIn("Hypothetical scenario", flat)
    elif kind == "sources":
        for section in ("analysis", "scenario", "observations"):
            for source in context[section]["source_refs"]:
                test.assertIn(source, flat)
        test.assertNotIn("Water budget period:", flat)
        test.assertNotIn("supplied score", flat)
    elif kind == "missing_candidates":
        test.assertIn("unknown", flat)
        test.assertNotRegex(flat, r"Candidate [\w-]+:")
    else:
        raise AssertionError(f"Unimplemented QA expectation {kind}")
